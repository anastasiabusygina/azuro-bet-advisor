#!/bin/bash
# Скрипт для сборки и проверки проекта

# Цвета для вывода
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Функция для вывода с временной меткой
log() {
  echo -e "${GREEN}[$(date +'%Y-%m-%d %H:%M:%S')]${NC} $1"
}

# Функция для ошибок
error() {
  echo -e "${RED}[$(date +'%Y-%m-%d %H:%M:%S')] ОШИБКА:${NC} $1"
  exit 1
}

# Функция для предупреждений
warn() {
  echo -e "${YELLOW}[$(date +'%Y-%m-%d %H:%M:%S')] ПРЕДУПРЕЖДЕНИЕ:${NC} $1"
}

# Проверка зависимостей
log "Проверка наличия зависимостей..."
if ! npm list > /dev/null 2>&1; then
  log "Устанавливаем зависимости..."
  npm install || error "Не удалось установить зависимости"
fi

# Очистка директории сборки
log "Очистка директории сборки..."
rm -rf dist/

# Сборка всего проекта
log "Сборка всего проекта..."
npm run build:all || warn "Сборка завершилась с предупреждениями"

# Запуск тестов
log "Запуск всех тестов..."
npm run test:all || warn "Некоторые тесты не прошли"

# Проверка компиляции
log "Проверка импортов и компиляции основного проекта..."
tsc --noEmit || warn "Проверка типов основного проекта обнаружила ошибки"

# Проверка компиляции скриптов
log "Проверка импортов и компиляции скриптов..."
tsc -p scripts/ts/tsconfig.json --noEmit || warn "Проверка типов скриптов обнаружила ошибки"

log "Сборка и проверка проекта завершены!"
exit 0 